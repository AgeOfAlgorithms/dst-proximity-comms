local M = {lang = "en"}

-- (modmain) the game's language: LOC.GetLanguage() -> LANGUAGE.*
function M.pick(langId)
    if langId == nil then M.lang = "en" return M.lang end
    local L = LANGUAGE or {}
    if langId == L.CHINESE_S or langId == L.CHINESE_S_RAIL or langId == L.CHINESE_T then M.lang = "zh"
    elseif langId == L.RUSSIAN then M.lang = "ru"
    else M.lang = "en" end
    return M.lang
end

function M.get(key)
    local t = STR[M.lang] or STR.en
    local v = t[key]
    if v == nil then v = STR.en[key] end
    return v
end

function M.L(key, ...)
    local v = M.get(key)
    if v == nil then return key end
    if select("#", ...) > 0 and type(v) == "string" then
        local ok, s = pcall(string.format, v, ...)
        if ok then return s end
    end
    return v
end

